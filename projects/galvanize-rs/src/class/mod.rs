//! Machinery for declaring class-like objects, see [`class`].

pub use galvanize_rs_macros::class;

/// Converts a class handle into a handle of the class itself or any class it
/// (transitively) extends.
///
/// Every `#[class]` implements this for itself and each of its ancestors. `I`
/// is an index the compiler infers to pick the right path through the
/// hierarchy, so leave it generic. To accept any class that extends `Animal`:
///
/// ```
/// use galvanize_rs::{Extends, Str, class};
///
/// #[class]
/// pub struct Animal {
///   pub name: Str,
/// }
///
/// #[class(extends = Animal)]
/// pub struct Dog {
///   pub good: bool,
/// }
///
/// fn name_of<I>(animal: impl Extends<Animal, I>) -> Str {
///   animal.upcast().name()
/// }
///
/// let animal = Animal::from_data(AnimalData { name: "Rex".into() });
/// let dog = Dog::from_data(DogData { base: animal.clone(), good: true });
/// assert_eq!(name_of(dog), "Rex");
/// assert_eq!(name_of(animal), "Rex");
/// ```
///
/// Classes also get an inherent `upcast` method, so calling it doesn't need
/// this trait in scope.
pub trait Extends<B, I> {
  /// Returns the handle of the `B` part of this object.
  fn upcast(&self) -> B;
}

impl<T: __private::Class> Extends<T, __private::Here> for T {
  fn upcast(&self) -> T {
    self.clone()
  }
}

impl<T, B, I> Extends<B, __private::There<I>> for T
where
  T: __private::SubClass,
  T::Base: Extends<B, I>,
{
  fn upcast(&self) -> B {
    self.base_ref().upcast()
  }
}

/// Implementation details of the `#[class]` macro. Not public API.
#[doc(hidden)]
pub mod __private {
  use core::fmt::DebugStruct;
  use core::marker::PhantomData;

  /// Marks a type generated by `#[class]`.
  #[diagnostic::on_unimplemented(message = "`{Self}` isn't a #[class]", label = "only a #[class] can be extended")]
  pub trait Class: Clone {}

  /// A class that extends another class.
  pub trait SubClass: Class {
    /// The class this one extends.
    type Base: Class;

    /// Returns the base part of this object.
    fn base_ref(&self) -> &Self::Base;
  }

  /// Writes the fields of a class, including those of its bases, so that
  /// `Debug` prints one flat struct.
  #[diagnostic::on_unimplemented(message = "`{Self}` isn't a #[class], or its fields don't implement `Debug`")]
  pub trait ClassDebug {
    fn fmt_fields(&self, d: &mut DebugStruct<'_, '_>);
  }

  /// [`super::Extends`] index for upcasting a class to itself.
  pub struct Here;

  /// [`super::Extends`] index for upcasting a class via its base, then `I`.
  pub struct There<I>(PhantomData<I>);
}
