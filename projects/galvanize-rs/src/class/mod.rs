//! Machinery for declaring classes, see [`class`] and [`class_methods`].

pub mod unsafe_runtime;

pub use galvanize_rs_macros::{class, class_methods};

/// Converts a class handle into a handle of the class itself or any class it
/// (transitively) extends.
///
/// Every `#[class]` implements this for itself and each of its ancestors. `I`
/// is an index the compiler infers to pick the right path through the
/// hierarchy, so leave it generic. To accept any class that extends `Animal`:
///
/// ```
/// use galvanize_rs::{Extends, Str, class, class_methods};
///
/// #[class(open)]
/// pub struct Animal {
///   pub name: Str,
/// }
///
/// #[class_methods]
/// impl Animal {}
///
/// #[class(extends = Animal)]
/// pub struct Dog {
///   pub good: bool,
/// }
///
/// #[class_methods]
/// impl Dog {
///   pub fn new(name: &str) -> Self {
///     Self::from_data(DogData { base: AnimalData { name: name.into() }, good: true })
///   }
/// }
///
/// fn name_of<I>(animal: impl Extends<Animal, I>) -> Str {
///   animal.upcast().name()
/// }
///
/// # fn main() {
/// let dog = Dog::new("Rex");
/// assert_eq!(name_of(dog.clone()), "Rex");
/// assert_eq!(name_of(dog.upcast::<Animal, _>()), "Rex");
/// # }
/// ```
///
/// Classes also get an inherent `upcast` method, so calling it doesn't need
/// this trait in scope.
pub trait Extends<B, I> {
  /// Returns a handle to the same object, viewed as a `B`.
  fn upcast(&self) -> B;
}

impl<T: __private::Class> Extends<T, __private::Here> for T {
  fn upcast(&self) -> T {
    self.clone()
  }
}

impl<T, B, I> Extends<B, __private::There<I>> for T
where
  T: __private::SubClass,
  T::Base: Extends<B, I>,
{
  fn upcast(&self) -> B {
    self.base_ref().upcast()
  }
}

mod sealed {
  pub trait Sealed {}
  impl Sealed for super::SafeRuntimeStrategy {}
  impl Sealed for super::UnsafeRuntimeStrategy {}
}

/// Selects how a class hierarchy is implemented, see
/// `#[class(runtime_strategy = ...)]`.
///
/// Both strategies generate the same API from the same declarations, so
/// switching between them doesn't require any other changes. The strategy is
/// chosen by a hierarchy's root class and inherited by every subclass.
///
/// This trait is sealed: [`SafeRuntimeStrategy`] and [`UnsafeRuntimeStrategy`]
/// are its only implementations.
pub trait RuntimeStrategy: sealed::Sealed + 'static {}

/// Implements classes without any `unsafe` code. This is the default.
///
/// Each class gets an object trait that the most-derived storage implements,
/// and a handle holds an `Arc` to that storage plus one view per ancestor.
/// Handles therefore grow with the depth of the hierarchy, and every call to
/// an override clones and drops an `Arc`, which contends when many threads
/// call methods on the same object.
#[derive(Debug, Clone, Copy, Default)]
pub struct SafeRuntimeStrategy;

impl RuntimeStrategy for SafeRuntimeStrategy {}

/// Implements classes with a small `unsafe` kernel, trading a maintenance
/// burden for speed.
///
/// Each object is one allocation whose storage embeds its parent's as a
/// `repr(C)` prefix, and virtual methods dispatch through a table of function
/// pointers, like C++, Java or GObject. Handles are four machine words at any
/// depth, cloning one is a single reference count increment, and virtual calls
/// don't write to any shared state, so they don't contend between threads.
///
/// The `unsafe` code lives in galvanize-rs and the templates of its macros,
/// never in your code, and is tested under Miri. Constructing a class takes a
/// read lock on a global table registry.
#[derive(Debug, Clone, Copy, Default)]
pub struct UnsafeRuntimeStrategy;

impl RuntimeStrategy for UnsafeRuntimeStrategy {}

/// The [`RuntimeStrategy`] used when none is specified.
pub type DefaultRuntimeStrategy = SafeRuntimeStrategy;

/// Implementation details of the class macros. Not public API.
#[doc(hidden)]
pub mod __private {
  use core::fmt::DebugStruct;
  use core::marker::PhantomData;

  pub use super::unsafe_runtime;
  pub use galvanize_rs_macros::{__complete, __inherit};

  /// Implemented by every type generated by `#[class]`.
  #[diagnostic::on_unimplemented(message = "`{Self}` isn't a #[class]", label = "expected a #[class]")]
  pub trait Class: Clone + Send + Sync + 'static {
    /// The address of the object's shared allocation, the same for every view of it.
    fn __identity(&self) -> *const ();
  }

  /// Implemented by classes declared with `#[class(open)]`, which may be extended.
  #[diagnostic::on_unimplemented(
    message = "`{Self}` isn't an open #[class], so it can't be extended",
    label = "declare it with #[class(open)] to allow subclasses"
  )]
  pub trait OpenClass: Class {}

  /// A class that extends another class.
  pub trait SubClass: Class {
    /// The class this one extends.
    type Base: Class;

    /// Returns this object viewed as its base class.
    fn base_ref(&self) -> &Self::Base;
  }

  /// Writes the fields of a class, including those of its ancestors, so that
  /// `Debug` prints one flat struct.
  #[diagnostic::on_unimplemented(message = "`{Self}` isn't a #[class], or its fields don't implement `Debug`")]
  pub trait ClassDebug {
    fn fmt_fields(&self, d: &mut DebugStruct<'_, '_>);
  }

  /// Implemented by every class's `XData`, when the fields of the class and its ancestors all implement
  /// `Default`. It builds the data for a class's generated `new()`, and for the `base` of its subclasses'.
  ///
  /// The macros bound it with `for<'__d> Field: Default`. As that bound isn't global, it's only checked
  /// where it's used, so classes with fields that aren't `Default` still compile, but can't call `new()`.
  #[diagnostic::on_unimplemented(
    message = "`{Self}` can't be defaulted, as one of its class's fields (or its ancestors') isn't `Default`",
    label = "a field type, or an ancestor's, doesn't implement `Default`"
  )]
  pub trait DefaultData: Sized {
    fn __default_data() -> Self;
  }

  /// [`super::Extends`] index for upcasting a class to itself.
  pub struct Here;

  /// [`super::Extends`] index for upcasting a class via its base, then `I`.
  pub struct There<I>(PhantomData<I>);

  /// Implemented by [`super::SafeRuntimeStrategy`] only. The class macro picks a generator from the
  /// strategy's name, then checks the name really is that strategy with this.
  #[diagnostic::on_unimplemented(
    message = "`{Self}` isn't `SafeRuntimeStrategy`",
    label = "name the runtime strategy directly, not through an alias"
  )]
  pub trait IsSafeRuntime: super::RuntimeStrategy {}
  impl IsSafeRuntime for super::SafeRuntimeStrategy {}

  /// Implemented by [`super::UnsafeRuntimeStrategy`] only, see [`IsSafeRuntime`].
  #[diagnostic::on_unimplemented(
    message = "`{Self}` isn't `UnsafeRuntimeStrategy`",
    label = "name the runtime strategy directly, not through an alias"
  )]
  pub trait IsUnsafeRuntime: super::RuntimeStrategy {}
  impl IsUnsafeRuntime for super::UnsafeRuntimeStrategy {}

  pub const fn assert_safe_runtime<R: IsSafeRuntime>() {}
  pub const fn assert_unsafe_runtime<R: IsUnsafeRuntime>() {}

  /// Implemented by `#[class_methods]` for the marker type `#[class]` declares, for the class's type
  /// parameters `P`. `Inner` is the hidden handle that the class wraps.
  #[diagnostic::on_unimplemented(
    message = "every #[class] needs a #[class_methods] block after it, in the same module",
    label = "add `#[class_methods] impl ... {{}}` after this struct, even if it's empty"
  )]
  pub trait HasClassMethods<P> {
    type Inner;
  }

  /// Fails to compile unless `C` may be extended.
  pub fn require_open<C: OpenClass>() {}
}
