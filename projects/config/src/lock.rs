//! `doup.lock`, which pins every package plugin of a repo's doup config to an exact version & content digest.
//!
//! It is written by `doup lock`, next to the repo's `doup.yaml`, & is meant to be committed. Its shape mirrors
//! wkg's `wkg.lock` (v1), plus the `size` of each package, which lets downloads report their progress.
//!
//! ```toml
//! version = 1
//!
//! [[packages]]
//! name = "doup:platform-plugin-github"
//!
//! [[packages.versions]]
//! requirement = "^0.1.0"
//! version = "0.1.0"
//! digest = "sha256:91ab6f3239a5b525b7d3ddca670f4cdabc0863ad1258041845774ee1b35c7425"
//! size = 1416040
//! ```

use crate::ConfigError;
use crate::repo::PackageSpec;
use semver::{Version, VersionReq};
use serde::{Deserialize, Serialize};
use std::io::Write;
use std::path::Path;

/// The name of the lock file, which lives next to the repo's doup config file.
pub const LOCK_FILE_NAME: &str = "doup.lock";

/// The only version of the lock file format there is so far.
pub const LOCK_FILE_VERSION: u64 = 1;

const HEADER: &str =
  "# This file is automatically generated by `doup lock`.\n# It is not intended for manual editing.\n";

/// The parsed contents of a `doup.lock` file. Packages are kept sorted, so that equal locks serialize identically.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct DoupLockFile {
  packages: Vec<LockedPackage>,
}

/// A package & every version of it that is locked, one per distinct requirement in the config.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
  /// The package without its version, eg: `doup:ecosystem-plugin-cargo`.
  pub name: String,

  /// The plugin's `registry`, exactly as written in the config. A different registry is a different package.
  #[serde(default, skip_serializing_if = "Option::is_none")]
  pub registry: Option<String>,

  pub versions: Vec<LockedVersion>,
}

/// The exact release a requirement was resolved to.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedVersion {
  /// The requirement from the config that this was resolved for.
  pub requirement: VersionReq,

  /// The version the requirement resolved to.
  pub version: Version,

  /// The digest of the package's content, eg: `sha256:<hex>`. Downloads that don't match are rejected.
  pub digest: String,

  /// The size of the package's content in bytes.
  pub size: u64,
}

/// The file as it is (de)serialized.
#[derive(Serialize, Deserialize)]
struct LockFileToml {
  version: u64,
  #[serde(default)]
  packages: Vec<LockedPackage>,
}

impl DoupLockFile {
  /// Every locked package, sorted by name & registry.
  pub fn packages(&self) -> &[LockedPackage] {
    &self.packages
  }

  /// Whether nothing is locked.
  pub fn is_empty(&self) -> bool {
    self.packages.is_empty()
  }

  /// The version locked for `spec`. Only an entry for the same registry & exact same requirement matches,
  /// so editing a plugin's version or registry in the config makes its entry stale.
  pub fn find(&self, spec: &PackageSpec<'_>) -> Option<&LockedVersion> {
    self
      .packages
      .iter()
      .find(|package| package.name == spec.name && package.registry.as_deref() == spec.registry)?
      .versions
      .iter()
      .find(|locked| locked.requirement == spec.requirement)
  }

  /// Locks `spec` to `locked`, replacing any entry for the same requirement.
  pub fn insert(&mut self, spec: &PackageSpec<'_>, locked: LockedVersion) {
    let index = match self
      .packages
      .iter()
      .position(|package| package.name == spec.name && package.registry.as_deref() == spec.registry)
    {
      Some(index) => index,
      None => {
        self.packages.push(LockedPackage {
          name: spec.name.to_string(),
          registry: spec.registry.map(str::to_string),
          versions: Vec::new(),
        });
        self.packages.len() - 1
      }
    };
    let versions = &mut self.packages[index].versions;
    versions.retain(|existing| existing.requirement != locked.requirement);
    versions.push(locked);
    self.normalize();
  }

  /// Sorts packages by name & registry, & their versions by requirement.
  fn normalize(&mut self) {
    for package in &mut self.packages {
      package.versions.sort_by_cached_key(|locked| locked.requirement.to_string());
    }
    self.packages.sort_by(|a, b| (&a.name, &a.registry).cmp(&(&b.name, &b.registry)));
  }

  /// Parses the contents of a lock file.
  ///
  /// # Errors
  ///
  /// [`ConfigError::ParseLock`] if it isn't valid, or [`ConfigError::UnsupportedLockVersion`]
  /// if it was written by a newer doup.
  pub fn from_toml(contents: &str) -> Result<Self, ConfigError> {
    let parsed: LockFileToml = toml::from_str(contents).map_err(ConfigError::ParseLock)?;
    if parsed.version != LOCK_FILE_VERSION {
      return Err(ConfigError::UnsupportedLockVersion { version: parsed.version });
    }
    let mut lock = Self { packages: parsed.packages };
    lock.normalize();
    Ok(lock)
  }

  /// Serializes the lock, header comment included.
  ///
  /// # Errors
  ///
  /// [`ConfigError::SerializeLock`], which should never happen in practice.
  pub fn to_toml(&self) -> Result<String, ConfigError> {
    let contents = LockFileToml { version: LOCK_FILE_VERSION, packages: self.packages.clone() };
    Ok(format!("{HEADER}{}", toml::to_string_pretty(&contents).map_err(ConfigError::SerializeLock)?))
  }

  /// Reads the lock file at `path`, `None` if there isn't one.
  ///
  /// # Errors
  ///
  /// [`ConfigError::ReadLock`] if it can't be read, or any error from [`Self::from_toml`] wrapped in
  /// [`ConfigError::File`] to name the file.
  pub fn load(path: &Path) -> Result<Option<Self>, ConfigError> {
    let contents = match std::fs::read_to_string(path) {
      Ok(contents) => contents,
      Err(err) if err.kind() == std::io::ErrorKind::NotFound => return Ok(None),
      Err(source) => return Err(ConfigError::ReadLock { path: path.to_path_buf(), source }),
    };
    Self::from_toml(&contents)
      .map(Some)
      .map_err(|source| ConfigError::File { path: path.to_path_buf(), source: Box::new(source) })
  }

  /// Writes the lock to `path`, atomically so that a concurrent reader never sees half a file.
  ///
  /// # Errors
  ///
  /// [`ConfigError::WriteLock`] if it can't be written.
  pub fn write(&self, path: &Path) -> Result<(), ConfigError> {
    let contents = self.to_toml()?;
    let write_err = |source| ConfigError::WriteLock { path: path.to_path_buf(), source };
    let dir = path.parent().filter(|dir| !dir.as_os_str().is_empty()).unwrap_or(Path::new("."));
    let mut file = tempfile::NamedTempFile::new_in(dir).map_err(write_err)?;
    file.write_all(contents.as_bytes()).map_err(write_err)?;
    file.persist(path).map_err(|err| write_err(err.error))?;
    Ok(())
  }
}

#[cfg(test)]
mod tests {
  use super::*;
  use assert_fs::{TempDir, prelude::*};

  fn spec<'a>(name: &'a str, requirement: &str, registry: Option<&'a str>) -> PackageSpec<'a> {
    PackageSpec { name, requirement: VersionReq::parse(requirement).unwrap(), registry }
  }

  fn locked(requirement: &str, version: &str) -> LockedVersion {
    LockedVersion {
      requirement: VersionReq::parse(requirement).unwrap(),
      version: Version::parse(version).unwrap(),
      digest: format!("sha256:{}", "a".repeat(64)),
      size: 42,
    }
  }

  #[test]
  fn find_matches_name_registry_and_requirement() {
    let mut lock = DoupLockFile::default();
    lock.insert(&spec("doup:cargo", "0.1.0", None), locked("0.1.0", "0.1.3"));
    lock.insert(&spec("doup:cargo", "0.1.0", Some("ghcr.io/acme")), locked("0.1.0", "0.1.1"));

    assert_eq!(lock.find(&spec("doup:cargo", "^0.1.0", None)).unwrap().version, Version::new(0, 1, 3));
    assert_eq!(lock.find(&spec("doup:cargo", "0.1.0", Some("ghcr.io/acme"))).unwrap().version, Version::new(0, 1, 1));
    assert_eq!(lock.find(&spec("doup:cargo", "0.2.0", None)), None);
    assert_eq!(lock.find(&spec("doup:cargo", "0.1.0", Some("ghcr.io/other"))), None);
    assert_eq!(lock.find(&spec("doup:github", "0.1.0", None)), None);
  }

  #[test]
  fn insert_replaces_the_same_requirement_only() {
    let mut lock = DoupLockFile::default();
    lock.insert(&spec("doup:cargo", "1", None), locked("1", "1.0.0"));
    lock.insert(&spec("doup:cargo", "2", None), locked("2", "2.0.0"));
    lock.insert(&spec("doup:cargo", "1", None), locked("1", "1.2.0"));
    let versions: Vec<_> = lock.packages()[0].versions.iter().map(|v| v.version.to_string()).collect();
    assert_eq!(versions, ["1.2.0", "2.0.0"]);
  }

  #[test]
  fn round_trips_through_a_file_regardless_of_insertion_order() {
    let mut a = DoupLockFile::default();
    a.insert(&spec("doup:github", "0.1.0", None), locked("0.1.0", "0.1.0"));
    a.insert(&spec("doup:cargo", "0.1.0", Some("ghcr.io/acme")), locked("0.1.0", "0.1.0"));
    let mut b = DoupLockFile::default();
    b.insert(&spec("doup:cargo", "0.1.0", Some("ghcr.io/acme")), locked("0.1.0", "0.1.0"));
    b.insert(&spec("doup:github", "0.1.0", None), locked("0.1.0", "0.1.0"));
    assert_eq!(a, b);
    assert_eq!(a.to_toml().unwrap(), b.to_toml().unwrap());

    let dir = TempDir::new().unwrap();
    let path = dir.child(LOCK_FILE_NAME);
    a.write(path.path()).unwrap();
    let toml = std::fs::read_to_string(path.path()).unwrap();
    assert!(toml.starts_with(HEADER) && toml.contains("[[packages.versions]]"), "{toml}");
    assert_eq!(DoupLockFile::load(path.path()).unwrap(), Some(a));
  }

  #[test]
  fn load_returns_none_for_a_missing_file() {
    let dir = TempDir::new().unwrap();
    assert_eq!(DoupLockFile::load(&dir.path().join(LOCK_FILE_NAME)).unwrap(), None);
  }

  #[test]
  fn rejects_other_versions_and_invalid_files() {
    assert!(matches!(DoupLockFile::from_toml("version = 2"), Err(ConfigError::UnsupportedLockVersion { version: 2 })));
    assert!(matches!(DoupLockFile::from_toml("version = [1"), Err(ConfigError::ParseLock(_))));
    let dir = TempDir::new().unwrap();
    let path = dir.child(LOCK_FILE_NAME);
    path.write_str("packages = 1").unwrap();
    let err = DoupLockFile::load(path.path()).unwrap_err();
    assert!(matches!(err, ConfigError::File { path: ref p, .. } if p == path.path()), "{err:?}");
  }
}
